def answer_messages(user_content: str, use_scoped_missing: bool = False, use_answer_variants: bool = False,
                    use_complete_answer: bool = False, use_conditional_first: bool = False,
                    use_applicability_guard: bool = False, use_actionable_gaps: bool = False,
                    use_historical_law_limit: bool = False, use_conditional_example: bool = False,
                    use_conditional_example_v2: bool = False, use_conditional_example_v3: bool = False, use_claim_discipline: bool = False,
                    use_norm_analysis: bool = False, use_typed_facts: bool = False,
                    use_minimal: bool = False) -> list[dict]:
    """Сообщения генератору (LLM #2): системный промпт, примеры на выдуманных документах, досье с вопросом."""
    system = ANSWER_SYSTEM
    if use_minimal:
        old_style = ANSWER_SYSTEM[ANSWER_SYSTEM.index("10. Стиль"):]
        system = system.replace(old_style, MINIMAL_RULE)
    if use_norm_analysis:
        system = system.replace(
            '"claims": [{"text": "утверждение — законченная фраза со ссылкой [[Д1.4]]",',
            '"analysis": "какие нормы досье относятся к вопросу и какие условия применимости установлены или не установлены фактами досье",\n'
            ' "claims": [{"text": "утверждение — законченная фраза со ссылкой [[Д1.4]]",')
    if use_typed_facts:
        system = system.replace(
            '"claims": [{"text": "утверждение — законченная фраза со ссылкой [[Д1.4]]",',
            '"facts": [{"значение": "число, дата или название", "единица": "день, месяц, процент, рубль, вид", '
            '"источник": "Д1.4", "условие": "редакция или условие из текста узла, пусто если их нет"}],\n'
            ' "claims": [{"text": "утверждение — законченная фраза со ссылкой [[Д1.4]]",')
    if use_conditional_first or use_conditional_example or use_conditional_example_v2 or use_conditional_example_v3:
        system = system.replace(
            'первое утверждение — прямой ответ на вопрос («Да.», «Нет.», значение, срок).',
            'первое утверждение — прямой ответ на вопрос. Если вывод зависит от неизвестного факта, '
            'сразу сформулируй ответ условно: отсутствие сведений не доказывает ни наличие, ни отсутствие события. '
            'Назови подтверждённые последствия каждого варианта со ссылками, а недостающий факт — в оговорке.')
    if use_complete_answer:
        old_style = ANSWER_SYSTEM[ANSWER_SYSTEM.index("10. Стиль"):]
        system = system.replace(old_style, COMPLETE_RULE)
    if use_answer_variants:
        old_rule = next(line for line in ANSWER_SYSTEM.splitlines() if line.startswith("9. "))
        system = system.replace('"answer" | "refuse" | "clarify"', '"answer" | "refuse"').replace(old_rule, Q19_RULE)
    if use_conditional_example_v2 or use_conditional_example_v3:
        system += "\n\nОтсутствие экземпляра документа у пользователя не доказывает, что событие не произошло; для расчёта требуй только необходимые данные, не дополнительные документы без основания."
    if use_conditional_example_v3:
        system += "\n\nОтсутствие условия в одном фрагменте не доказывает отсутствия ограничения, запрета, обязательства или документа в других источниках. Не делай разрешения или безусловного отрицательного вывода из молчания; если это важно, укажи лишь границу показанного текста."
    if use_historical_law_limit:
        system += "\n\n" + HISTORICAL_LAW_LIMIT_RULE
    if use_actionable_gaps:
        system += "\n\n" + ACTIONABLE_GAPS_RULE
    if use_applicability_guard:
        system += "\n\n" + APPLICABILITY_RULE
    if use_scoped_missing:
        system += "\n\n" + SCOPED_MISSING_RULE
    if use_claim_discipline:
        system += "\n\n" + CLAIM_DISCIPLINE_RULE
    if use_norm_analysis:
        system += "\n\n" + NORM_ANALYSIS_RULE
    if use_typed_facts:
        system += "\n\n" + TYPED_FACTS_RULE
    messages = [{"role": "system", "content": system}]
    for example_in, example_out in ANSWER_EXAMPLES:
        messages.append({"role": "user", "content": example_in})
        messages.append({"role": "assistant", "content": example_out})
    if use_conditional_example or use_conditional_example_v2 or use_conditional_example_v3:
        messages.extend([{"role": "user", "content": CONDITIONAL_EXAMPLE_IN},
                         {"role": "assistant", "content": CONDITIONAL_EXAMPLE_OUT}])
    if use_conditional_example_v2 or use_conditional_example_v3:
        messages.extend([{"role": "user", "content": CONDITIONAL_DOCUMENT_IN},
                         {"role": "assistant", "content": CONDITIONAL_DOCUMENT_OUT}])
    messages.append({"role": "user", "content": user_content})
    return messages


