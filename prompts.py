ROUTER_SUBQUERIES_NOTE = (
    "ДОПОЛНИТЕЛЬНОЕ ПОЛЕ \"subqueries\": список из 0–3 самостоятельных поисковых подзапросов. Заполняй, если ответ "
    "требует нескольких положений: разные документы или статьи, общее правило и исключение, условие и последствие "
    "(санкция, срок, порядок), сравнение вариантов. Каждый подзапрос — отдельный аспект, сформулированный полностью "
    "(с названием документа или статьи, если они известны). Для простого вопроса об одном положении — [].")

ROUTER_STEPBACK_NOTE = (
    "ДОПОЛНИТЕЛЬНОЕ ПОЛЕ \"stepback\": один более общий вопрос «шаг назад» — абстракция вопроса сотрудника для "
    "поиска общей нормы, когда конкретная ситуация в документах сформулирована шире или иначе. Отвечать на него "
    "не нужно: он только направляет поиск. Если общая норма совпадает по формулировке с вопросом — пустая строка.")


def router_messages(last_user: str, history: str, inventory: str, hints: dict,
                    subqueries: bool = False, stepback: bool = False) -> list[dict]:
    """Сообщения для роутера (LLM #1, 03b §1.3)."""
    parts = [f"ОПИСЬ БАЗЫ:\n{inventory}"]
    if history:
        parts.append(f"ИСТОРИЯ:\n{history}")
    parts.append(f"ПОДСКАЗКИ (найдено кодом, может быть неполно):\n{json.dumps(hints, ensure_ascii=False)}")
    parts.append(f"ВОПРОС:\n{last_user}")
    system = ROUTER_SYSTEM + ("\n\n" + ROUTER_SUBQUERIES_NOTE if subqueries else "") \
        + ("\n\n" + ROUTER_STEPBACK_NOTE if stepback else "")
    return [{"role": "system", "content": system}, {"role": "user", "content": "\n\n".join(parts)}]


